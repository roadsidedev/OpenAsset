#!/usr/bin/env node
const fs = require("fs");
const path = require("path");

const args = process.argv.slice(2);
const value = (flag) => {
  const index = args.indexOf(flag);
  return index >= 0 ? args[index + 1] : undefined;
};
const type = value("--type") || "oracle";
const name = value("--name") || "MyAdapter";
const allowed = ["asset", "oracle", "compliance", "liquidation", "position"];
if (!allowed.includes(type) || !/^[A-Za-z][A-Za-z0-9]*$/.test(name)) {
  console.error(`Usage: create-openasset-adapter --type <${allowed.join("|")}> --name <PascalCaseName>`);
  process.exit(1);
}

const root = path.resolve(process.cwd(), name);
if (fs.existsSync(root)) {
  console.error(`Refusing to overwrite existing directory: ${root}`);
  process.exit(1);
}
fs.mkdirSync(path.join(root, "contracts"), { recursive: true });
const interfaceName = {
  asset: "IAssetAdapter",
  oracle: "IOracleAdapter",
  compliance: "IComplianceAdapter",
  liquidation: "ILiquidationAdapter",
  position: "IPositionAdapterInit",
}[type];
const configure = type === "asset" || type === "oracle"
  ? "configure(address market, address asset)"
  : type === "liquidation"
    ? "configure(address market, address assetAdapter)"
    : "configure(address market)";
const source = `// SPDX-License-Identifier: MIT
pragma solidity ^0.8.20;

import "@openasset/adapter-sdk/contracts/interfaces/${interfaceName}.sol";

/**
 * @notice Starter ${type} adapter generated by @openasset/adapter-sdk.
 * @dev Add a marketConfigs mapping, restrict ${configure} to the factory,
 *      and implement fail-closed behavior before deploying.
 */
abstract contract ${name} is ${interfaceName} {
    address public immutable factory;

    constructor(address factoryAddress) {
        require(factoryAddress != address(0), "Invalid factory");
        factory = factoryAddress;
    }

    // TODO: implement ${interfaceName} and add the SDK test matrix.
}
`;
fs.writeFileSync(path.join(root, "contracts", `${name}.sol`), source);
const readme = "# " + name + "\n\nGenerated with @openasset/adapter-sdk. Implement `" + interfaceName + "`, add multi-tenant configuration, and run the verification checklist before registration.\n";
fs.writeFileSync(path.join(root, "README.md"), readme);
console.log(`Created ${root}`);
